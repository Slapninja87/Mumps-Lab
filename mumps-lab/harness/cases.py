"""Parse case headers and render the case catalog.

Run `python3 -m harness.cases > CATALOG.md` to regenerate the catalog.
"""
from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

CASES_DIR = Path(__file__).resolve().parent.parent / "cases"

REQUIRED_FIELDS = ("title", "kind", "naive", "why", "verified")
VALID_KINDS = ("works", "breaks", "security")
_HEADER_PREFIX = " ;@"


class CaseFormatError(ValueError):
    """A case file has missing, unknown, or malformed header metadata."""


@dataclass(frozen=True)
class Case:
    name: str
    title: str
    kind: str
    naive: str
    why: str
    verified: str
    source: str
    expected: str


def parse_case(path: Path) -> Case:
    source = path.read_text(encoding="utf-8")
    fields: dict[str, str] = {}
    for line in source.splitlines():
        if not line.startswith(_HEADER_PREFIX):
            continue
        key, _, value = line[len(_HEADER_PREFIX):].partition(" ")
        if key in fields:
            raise CaseFormatError(f"{path.name}: duplicate header field '{key}'")
        fields[key] = value.strip()

    unknown = sorted(set(fields) - set(REQUIRED_FIELDS))
    if unknown:
        raise CaseFormatError(f"{path.name}: unknown header fields {unknown}")
    missing = [field for field in REQUIRED_FIELDS if not fields.get(field)]
    if missing:
        raise CaseFormatError(f"{path.name}: missing or empty header fields {missing}")
    if fields["kind"] not in VALID_KINDS:
        raise CaseFormatError(
            f"{path.name}: kind '{fields['kind']}' is not one of {VALID_KINDS}"
        )

    expected_path = path.with_suffix(".expected")
    if not expected_path.is_file():
        raise CaseFormatError(f"{path.name}: missing {expected_path.name}")

    return Case(
        name=path.stem,
        title=fields["title"],
        kind=fields["kind"],
        naive=fields["naive"],
        why=fields["why"],
        verified=fields["verified"],
        source=source,
        expected=expected_path.read_text(encoding="utf-8"),
    )


def load_cases(cases_dir: Path = CASES_DIR) -> list[Case]:
    routine_names = {path.stem for path in cases_dir.glob("*.m")}
    orphans = sorted(
        path.name for path in cases_dir.glob("*.expected") if path.stem not in routine_names
    )
    if orphans:
        raise CaseFormatError(f"Expected-output files with no routine: {orphans}")
    return [parse_case(cases_dir / f"{name}.m") for name in sorted(routine_names)]


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_catalog(cases: list[Case]) -> str:
    lines = [
        "# Case catalog",
        "",
        "Generated by `python3 -m harness.cases`. Do not edit by hand.",
        "",
        "| Case | Kind | Title | What people expect | What actually happens and why | Verified on |",
        "|---|---|---|---|---|---|",
    ]
    for case in cases:
        lines.append(
            f"| `{case.name}` | {case.kind} | {_cell(case.title)} | {_cell(case.naive)} "
            f"| {_cell(case.why)} | {_cell(case.verified)} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render_catalog(load_cases()))
